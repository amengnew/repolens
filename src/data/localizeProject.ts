function tr(value: string) {
  return zhText[value] ?? value;
}

export function localizeProject(project: Project, language: Language): Project {
  if (language === 'en') return project;

  return {
    ...project,
    summary: tr(project.summary),
    complexity: project.complexity.map((metric) => ({
      ...metric,
      label: tr(metric.label),
      detail: tr(metric.detail),
    })),
    coreModules: project.coreModules.map(tr),
    entries: project.entries.map((entry) => ({
      ...entry,
      name: tr(entry.name),
      role: tr(entry.role) as Project['entries'][number]['role'],
      input: tr(entry.input),
      auth: tr(entry.auth),
      permissions: entry.permissions.map(tr),
    })),
    flows: project.flows.map((flow) => ({
      ...flow,
      name: tr(flow.name),
      trigger: tr(flow.trigger),
      description: tr(flow.description),
      nodes: flow.nodes.map((node) => ({
        ...node,
        label: tr(node.label),
        description: tr(node.description),
      })),
      errorPaths: flow.errorPaths.map(tr),
    })),
    decisions: project.decisions.map((decision) => ({
      ...decision,
      title: tr(decision.title),
      topic: tr(decision.topic),
      problem: tr(decision.problem),
      solution: tr(decision.solution),
      parameters: decision.parameters.map((parameter) => ({
        ...parameter,
        key: tr(parameter.key),
      })),
      rationale: tr(decision.rationale),
      alternatives: decision.alternatives.map(tr),
      tradeoffs: decision.tradeoffs.map(tr),
    })),
    learningPath: project.learningPath.map((step) => ({
      ...step,
      title: tr(step.title),
      duration: tr(step.duration),
      summary: tr(step.summary),
    })),
    askSamples: project.askSamples.map((sample) => ({
      ...sample,
      question: tr(sample.question),
      answer: tr(sample.answer),
    })),
    evidence: project.evidence.map((item) => ({
      ...item,
      label: tr(item.label),
    })),
  };
}
